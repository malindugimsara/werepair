        function displayToast(heading, text, icon, loaderBg) {
            $.toast({
                heading: heading,
                text: text,
                position: "bottom-right",
                loaderBg: loaderBg,
                icon: icon,
                hideAfter: 15000,
                stack: 3,
            });
        }

        function form_submit() {
            var btn = document.getElementById("form-btn");
            var originalBtnHtml = '<span>Send Message</span> <i class="fa-solid fa-paper-plane"></i>';
            btn.disabled = true;
            btn.innerHTML = '<span>Sending Message...</span> <i class="fa-solid fa-spinner fa-spin"></i>';

            // Business Information - Get values by ID
            var name = document.getElementById('name').value;
            var email = document.getElementById('email').value;
            var phone = document.getElementById('phone').value;
            var subject = document.getElementById('subject').value;
            var message = document.getElementById('message').value;

            var form = new FormData();
            var hp = document.getElementById('website_hp') ? document.getElementById('website_hp').value : '';

            // Append all values to FormData
            form.append("name", name);
            form.append("email", email);
            form.append("phone", phone);
            form.append("subject", subject);
            form.append("message", message);
            form.append("website_hp", hp);

            // Creating and sending the AJAX request
            var r = new XMLHttpRequest();
            r.onreadystatechange = function() {
                if (r.readyState == 4) {
                    btn.disabled = false;
                    btn.innerHTML = originalBtnHtml;
                    var t = r.responseText.trim();
                    if (t == "Fill in the all fields!") {
                        displayToast("Error", t, "error", "#c46a69");
                    } else if (t == "success") {
                        displayToast("Success", "Thank you for contacting us. We’ll get back to you shortly.", "success", "#3b7f5e");
                        document.getElementById("c-f").classList.add("d-none");
                        document.getElementById("th-c-f").classList.remove("d-none");
                    } else {
                        displayToast("Error", t || "Please try again later!", "error", "#c46a69");
                    }
                }
            }

            r.open("POST", "inc/send-mail/contact-send-email.php", true);
            r.send(form);
        }
    </script>

